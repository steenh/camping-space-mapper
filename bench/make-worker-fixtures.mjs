// Writes bench/fixtures/worker-bench.json: the synthetic zones and products used by the browser
// benchmark bench/browser/worker-bench.html (fase 0B.4). Synthetic data only (bench/lib/fixtures.mjs).
// Usage: node bench/make-worker-fixtures.mjs
import fs from 'node:fs';
import { SIMPLE_SHAPES, PRODUCTS, polygonFeature } from './lib/fixtures.mjs';

const ZONES = ['D_irregular', 'E_strip_62x400'];
const out = {
  note: 'Synthetic fixtures from bench/lib/fixtures.mjs (no RF data). Generated by bench/make-worker-fixtures.mjs.',
  zones: Object.fromEntries(ZONES.map(name => [name, polygonFeature(SIMPLE_SHAPES[name])])),
  products: PRODUCTS,
};
fs.mkdirSync('bench/fixtures', { recursive: true });
fs.writeFileSync('bench/fixtures/worker-bench.json', JSON.stringify(out, null, 1) + '\n');
console.log(`bench/fixtures/worker-bench.json: ${ZONES.join(', ')} × ${Object.keys(PRODUCTS).join(', ')}`);
